/**
 * Pure mapping + validation for disclosure-requirement imports.
 *
 * Frameworks get revised, and the seeded catalog deliberately stops short of
 * datapoint-level detail for the larger standards (ESRS alone runs to roughly a
 * thousand datapoints — inventing them in a compliance tool is worse than
 * leaving them out). This importer is how an organization loads that detail, or
 * amends a framework after a revision, without a code change.
 *
 * Pure and dependency-free so it is unit-testable.
 */

import { METRIC_KEYS } from './disclosure-metrics-core';

export interface MappedRequirementRow {
  framework_code: string;
  requirement_code: string;
  section: string | null;
  title: string;
  description: string | null;
  response_type: 'narrative' | 'metric' | 'both';
  metric_key: string | null;
  sort_order: number;
}

/**
 * Material topics this requirement belongs to, for the materiality gate
 * (migration 017). Kept off `MappedRequirementRow` because it writes to a
 * different table.
 *
 *   undefined  — the column was blank: leave existing links untouched.
 *   []         — the literal 'none': clear the links, making the requirement
 *                unconditional.
 *   [...]      — replace the links with exactly these topics.
 *
 * A blank cell means "no change" rather than "clear" so that re-importing a
 * file produced before this column existed cannot silently un-scope a
 * framework. Clearing has to be asked for.
 */
export type TopicCodesDirective = string[] | undefined;

export type RequirementRowResult =
  | { ok: true; row: MappedRequirementRow; topicCodes: TopicCodesDirective }
  | { ok: false; error: string };

export const REQUIREMENT_IMPORT_COLUMNS = [
  'framework_code', 'requirement_code', 'section', 'title',
  'description', 'response_type', 'metric_key', 'sort_order', 'topic_codes',
] as const;

const RESPONSE_TYPES = ['narrative', 'metric', 'both'];

/** Downloadable template with the header and two illustrative rows. */
export function requirementImportTemplate(): string {
  const header = REQUIREMENT_IMPORT_COLUMNS.join(',');
  const example1 = [
    'CSRD', 'E5-5', 'ESRS E5 — Resource use', 'Resource outflows',
    'Waste generated by composition and treatment route.', 'both', 'waste_total', '40', 'E5',
  ].join(',');
  const example2 = [
    'CSRD', 'E3-4', 'ESRS E3 — Water', 'Water consumption',
    'Total water consumption and consumption in areas of water stress.', 'both', 'water_consumption', '30', 'E3',
  ].join(',');
  return `${header}\n${example1}\n${example2}\n`;
}

/**
 * Parse the `topic_codes` cell. Multiple topics are separated by `;` — not `,`,
 * which is the CSV delimiter.
 */
function parseTopicCodes(raw: string): { ok: true; value: TopicCodesDirective } | { ok: false; error: string } {
  const trimmed = raw.trim();
  if (!trimmed) return { ok: true, value: undefined };
  if (trimmed.toLowerCase() === 'none') return { ok: true, value: [] };

  const codes = trimmed.split(';').map((c) => c.trim()).filter(Boolean);
  if (codes.length === 0) {
    return { ok: false, error: 'topic_codes contains only separators. Leave it blank, or use "none" to clear the links.' };
  }
  const duplicates = codes.filter((c, i) => codes.indexOf(c) !== i);
  if (duplicates.length > 0) {
    return { ok: false, error: `topic_codes repeats ${duplicates[0]}.` };
  }
  return { ok: true, value: codes };
}

/**
 * Map one normalized CSV row to a disclosure requirement. The framework's
 * existence is checked server-side against the caller's catalog; this validates
 * shape only.
 */
export function mapRequirementCsvRow(row: Record<string, string>): RequirementRowResult {
  const frameworkCode = (row.framework_code ?? '').trim();
  if (!frameworkCode) return { ok: false, error: 'framework_code is required.' };

  const requirementCode = (row.requirement_code ?? '').trim();
  if (!requirementCode) return { ok: false, error: 'requirement_code is required.' };

  const title = (row.title ?? '').trim();
  if (!title) return { ok: false, error: 'title is required.' };

  const responseTypeRaw = (row.response_type ?? '').trim().toLowerCase() || 'narrative';
  if (!RESPONSE_TYPES.includes(responseTypeRaw)) {
    return {
      ok: false,
      error: `response_type must be one of: ${RESPONSE_TYPES.join(', ')}. Got "${row.response_type}".`,
    };
  }

  const metricKeyRaw = (row.metric_key ?? '').trim();
  if (metricKeyRaw && !(METRIC_KEYS as readonly string[]).includes(metricKeyRaw)) {
    return {
      ok: false,
      error: `Unknown metric_key "${metricKeyRaw}". A requirement can only be auto-answered by a metric the platform computes: ${METRIC_KEYS.join(', ')}.`,
    };
  }

  // A requirement typed 'metric' with no metric_key could never be satisfied
  // by data, which is a silent dead end rather than a visible gap.
  if (responseTypeRaw === 'metric' && !metricKeyRaw) {
    return {
      ok: false,
      error: 'response_type "metric" requires a metric_key, otherwise the requirement can never be answered from data.',
    };
  }

  const sortOrderRaw = (row.sort_order ?? '').trim();
  let sortOrder = 0;
  if (sortOrderRaw) {
    const parsed = Number(sortOrderRaw);
    if (!Number.isInteger(parsed)) {
      return { ok: false, error: `sort_order must be a whole number, got "${sortOrderRaw}".` };
    }
    sortOrder = parsed;
  }

  const topicCodes = parseTopicCodes(row.topic_codes ?? '');
  if (!topicCodes.ok) return { ok: false, error: topicCodes.error };

  return {
    ok: true,
    row: {
      framework_code: frameworkCode,
      requirement_code: requirementCode,
      section: (row.section ?? '').trim() || null,
      title,
      description: (row.description ?? '').trim() || null,
      response_type: responseTypeRaw as MappedRequirementRow['response_type'],
      metric_key: metricKeyRaw || null,
      sort_order: sortOrder,
    },
    topicCodes: topicCodes.value,
  };
}
